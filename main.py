#!/usr/bin/env python3
"""One line of earned pride.

Prints a single sentence: pride earned through real work,
not vanity -- a finished thing, built by hand, holding weight.
"""

LINE = (
    "My hands still smell of sawdust, but the chair I built "
    "holds my father's weight without a single creak."
)


def main() -> None:
    print(LINE)


if __name__ == "__main__":
    main()
